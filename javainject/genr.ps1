# Generate com/matou/mtbox/music/R.java from public.xml + built APK resource table.
#
# Two sources are needed:
#   public.xml  - the 6000+ pre-existing resources, including colors that
#                 "aapt2 dump resources" does not enumerate on their own
#   aapt2 dump  - resources added in this round; apktool does not write their
#                 new ids back into public.xml, they only exist in the build output
# The second source overrides the first, so the ids end up being exactly the ones
# used at runtime.
#
# NOTE: comments in this file are deliberately ASCII-only. PowerShell 5.1 reads
# .ps1 as the system ANSI codepage when there is no BOM, and mangled multi-byte
# characters inside comments produce stray " { } characters that break parsing.
#
# Usage:
#   powershell -File D:\MTBOX\javainject\genr.ps1
#   powershell -File D:\MTBOX\javainject\genr.ps1 -Apk <freshly built.apk>

param(
    [string]$Apk = 'C:\Users\Administrator\AppData\Local\Temp\opencode\idpass.apk',
    [string]$Package = 'com.matou.mtbox.music'
)

$ErrorActionPreference = 'Stop'

$aapt2     = 'D:\MTBOX\Android\build-tools\37.0.0\aapt2.exe'
$publicXml = 'D:\MTBOX\work_fong\res\values\public.xml'
$outDir    = 'D:\MTBOX\javainject\src\com\matou\mtbox\music'
$outFile   = Join-Path $outDir 'R.java'

if (-not (Test-Path $Apk)) { throw "APK not found: $Apk" }
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

# type -> @{ name -> "0x........" }
$byType = New-Object 'System.Collections.Hashtable'

function Add-Res {
    param([string]$Type, [string]$Name, [string]$Id)
    # Resource names may contain characters that are illegal in a Java identifier,
    # e.g. "AlertDialog.AppCompat" or names starting with a digit.
    $field = ($Name -replace '[^A-Za-z0-9_]', '_')
    if ($field -match '^[0-9]') { $field = '_' + $field }
    if (-not $byType.ContainsKey($Type)) {
        $byType[$Type] = New-Object 'System.Collections.Hashtable'
    }
    $byType[$Type][$field] = $Id
}

if (Test-Path $publicXml) {
    $xml = [xml](Get-Content $publicXml -Raw)
    foreach ($n in $xml.resources.public) {
        Add-Res ([string]$n.type) ([string]$n.name) ([string]$n.id)
    }
    Write-Host ("public.xml : {0} types" -f $byType.Keys.Count)
}

foreach ($line in (& $aapt2 dump resources $Apk)) {
    if ($line -match '^\s*resource 0x([0-9a-fA-F]{8}) ([\w\-\.]+)/([\w\.]+)') {
        Add-Res $Matches[2] $Matches[3] ('0x' + $Matches[1])
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("package $Package;")
[void]$sb.AppendLine()
[void]$sb.AppendLine("// generated by genr.ps1 - do not edit")
[void]$sb.AppendLine("public final class R {")

$total = 0
foreach ($type in ($byType.Keys | Sort-Object)) {
    # Must be a nested class named "id"/"layout"/..., not a flat identifier
    # containing '$'. "class R$id" is a single identifier and would not
    # satisfy R.id references in the Java sources.
    $cls = ($type -replace '[^A-Za-z0-9_]', '_')
    [void]$sb.AppendLine("    public static final class $cls {")
    $map = $byType[$type]
    foreach ($name in ($map.Keys | Sort-Object)) {
        [void]$sb.AppendLine("        public static final int $name = " + $map[$name] + ";")
        $total++
    }
    [void]$sb.AppendLine("    }")
}
[void]$sb.AppendLine("}")

[System.IO.File]::WriteAllText($outFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("wrote {0} : {1} consts / {2} types" -f $outFile, $total, $byType.Keys.Count)